// 전체 마이너 아르카나
export const MINOR_ARCANA: MinorArcanaCard[] = [
  ...WANDS,
  ...CUPS,
  ...SWORDS,
  ...PENTACLES,
];

// 슈트별 조회 유틸
export function getCardBySuit(suit: MinorArcanaCard['suit']): MinorArcanaCard[] {
  return MINOR_ARCANA.filter(c => c.suit === suit);
}

// 이름으로 카드 조회
export function getCardByName(koreanName: string): MinorArcanaCard | undefined {
  return MINOR_ARCANA.find(c => c.koreanName === koreanName);
}

// 숫자/코트 카드로 조회
export function getCardByNumber(suit: MinorArcanaCard['suit'], number: MinorArcanaCard['number']): MinorArcanaCard | undefined {
  return MINOR_ARCANA.find(c => c.suit === suit && c.number === number);
}

// 카드 해석을 프롬프트 컨텍스트로 변환
export function formatMinorArcanaForPrompt(
  card: MinorArcanaCard,
  isReversed: boolean,
  context: 'general' | 'love' | 'career' | 'money' = 'general'
): string {
  const direction = isReversed ? card.reversed : card.upright;
  return `[${card.koreanName} (${isReversed ? '역방향' : '정방향'})] ${direction[context]}`;
}
